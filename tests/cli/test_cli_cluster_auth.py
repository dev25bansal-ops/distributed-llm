"""Regression tests for the CLI's ability to talk to its own cluster.

Two defects found by driving the real commands, not by reading code:

1. ``distllm cluster start`` runs a server whose auth middleware mints an API
   key, but nothing persisted it and the CLI never sent one -- so every
   ``distllm model …`` command returned 401 against a cluster the user had just
   started themselves. The key was also minted by a *different* key store
   (core.api_key_store) than the one that wrote a file (api.middleware), so a
   fix on either side alone was not enough.

2. ``distllm cli-doctor`` died with UnicodeEncodeError on any console that
   cannot encode ``≥`` (Windows cp1252, C locale), losing all output while
   still exiting 0.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pytest


@pytest.fixture()
def key_file(tmp_path, monkeypatch):
    path = tmp_path / "api_key"
    monkeypatch.setenv("DISTLLM_KEY_FILE", str(path))
    monkeypatch.delenv("DISTLLM_API_KEY", raising=False)
    monkeypatch.delenv("API_KEY", raising=False)
    return path


class TestAutoGeneratedKeyIsShared:
    """The server mints a key; the CLI must be able to find it."""

    def test_key_store_persists_auto_generated_key(self, key_file):
        from distllm.core.api_key_store import ApiKeyStore

        store = ApiKeyStore()
        store._load()

        assert key_file.exists(), "auto-generated key was not persisted"
        written = key_file.read_text(encoding="utf-8").strip()
        assert written, "persisted key file is empty"
        # The persisted key must be the one this store will accept.
        assert store.authenticate(written) is not None

    def test_cli_reads_the_persisted_key(self, key_file):
        from distllm.cli.models import _resolve_api_key

        key_file.write_text("secret-from-file\n", encoding="utf-8")
        assert _resolve_api_key() == "secret-from-file"

    def test_cli_sends_the_key_as_bearer(self, key_file):
        from distllm.cli.models import _get_client

        key_file.write_text("secret-from-file", encoding="utf-8")
        with _get_client("127.0.0.1", 8000) as client:
            assert client.headers["Authorization"] == "Bearer secret-from-file"

    def test_environment_overrides_the_file(self, key_file, monkeypatch):
        from distllm.cli.models import _resolve_api_key

        key_file.write_text("from-file", encoding="utf-8")
        monkeypatch.setenv("DISTLLM_API_KEY", "from-env")
        assert _resolve_api_key() == "from-env"

    def test_missing_key_file_is_not_an_error(self, key_file):
        from distllm.cli.models import _resolve_api_key

        assert _resolve_api_key() is None

    def test_no_key_means_no_authorization_header(self, key_file):
        from distllm.cli.models import _get_client

        with _get_client("127.0.0.1", 8000) as client:
            assert "Authorization" not in client.headers


class TestUnicodeOutput:
    """A console that cannot encode the CLI's symbols must not crash it."""

    def test_cli_doctor_survives_cp1252_stdout(self):
        """cli-doctor writes ≥; it must not raise on a legacy-codepage console."""
        env = dict(os.environ)
        env["PYTHONIOENCODING"] = "cp1252"
        proc = subprocess.run(
            [sys.executable, "-m", "distllm.cli.main", "cli-doctor"],
            capture_output=True,
            text=True,
            timeout=300,
            env=env,
        )
        combined = (proc.stdout or "") + (proc.stderr or "")
        assert "UnicodeEncodeError" not in combined, combined[-800:]
        assert "charmap" not in combined, combined[-800:]

    def test_main_reconfigures_streams(self):
        """Importing the CLI entry module must force UTF-8 on its streams."""
        proc = subprocess.run(
            [
                sys.executable,
                "-c",
                "import sys; sys.path.insert(0,'src'); "
                "import distllm.cli.main as m; "
                "print(m.sys.stdout.encoding.lower().replace('-',''))",
            ],
            capture_output=True,
            text=True,
            timeout=180,
            cwd=str(Path(__file__).resolve().parents[3]),
        )
        assert "utf8" in (proc.stdout or "").lower(), proc.stdout + proc.stderr