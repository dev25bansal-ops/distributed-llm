function generateDockerCompose(config) {
    const { gpus, model, quantization, network, security } = config;
    const gpu = GPU_OPTIONS.find(g => g.id === gpus.gpuType);
    const modelInfo = MODEL_OPTIONS.find(m => m.id === model.model);
    const quant = QUANTIZATION_OPTIONS.find(q => q.id === quantization.level);

    const isSecure = security.preset !== 'development';
    const authEnv = isSecure ? `
      - API_KEY=\${API_KEY:-changeme}` : '';
    const tlsEnv = isSecure ? `
      - TLS_CERT_PATH=/certs/server.crt
      - TLS_KEY_PATH=/certs/server.key` : '';

    let compose = `# docker-compose.yml
# Generated by DistLLM Deployment Configurator
# GPU: ${gpu.name} x ${gpus.count}
# Model: ${modelInfo.name} (${quant.name})

version: '3.8'

services:
  coordinator:
    image: ghcr.io/distributed-llm/coordinator:latest
    container_name: distllm-coordinator
    restart: unless-stopped
    ports:
      - "8000:8000"
      - "50050:50050"
    environment:${authEnv}${tlsEnv}
      - DISTLLM_MODEL=${modelInfo.id}
      - DISTLLM_QUANTIZATION=${quant.id}
      - DISTLLM_NETWORK_MODE=${network.type}
    volumes:
      - ./models:/models
      - ./config:/config${isSecure ? '\n      - ./certs:/certs:ro' : ''}
    command: >
      distllm cluster start
        --model ${modelInfo.id}
        --quantization ${quant.id}
        --port 50050
        --api-port 8000
        ${isSecure ? '--auth api-key' : '--no-auth'}
        ${network.type === 'wan' ? '--wan --transport quic' : ''}
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:8000/health"]
      interval: 30s
      timeout: 10s
      retries: 3
      start_period: 40s
    deploy:
      resources:
        reservations:
          devices:
            - driver: nvidia
              count: 1
              capabilities: [gpu]
`;

    // Add workers
    const workerCount = Math.min(gpus.count - 1, 7);
    for (let i = 1; i <= workerCount; i++) {
        compose += `
  worker${i}:
    image: ghcr.io/distributed-llm/worker:latest
    container_name: distllm-worker-${i}
    restart: unless-stopped
    depends_on:
      coordinator:
        condition: service_healthy
    environment:${authEnv}
      - DISTLLM_COORDINATOR=coordinator:50050
      - DISTLLM_NODE_ID=worker-${i}
    volumes:
      - ./models:/models
    command: >
      distllm cluster join
        --coordinator coordinator
        --port 50050
        --node-id worker-${i}
        ${isSecure ? '--api-key \${API_KEY:-changeme}' : ''}
    deploy:
      resources:
        reservations:
          devices:
            - driver: nvidia
              device_ids: ["${i - 1}"]
              capabilities: [gpu]
`;
    }

    // Add monitoring if production
    if (security.preset === 'production') {
        compose += `
  prometheus:
    image: prom/prometheus:latest
    container_name: distllm-prometheus
    restart: unless-stopped
    ports:
      - "9090:9090"
    volumes:
      - ./monitoring/prometheus.yml:/etc/prometheus/prometheus.yml
      - prometheus_data:/prometheus

  grafana:
    image: grafana/grafana:latest
    container_name: distllm-grafana
    restart: unless-stopped
    ports:
      - "3000:3000"
    environment:
      - GF_SECURITY_ADMIN_PASSWORD=\${GRAFANA_PASSWORD:-admin}
    volumes:
      - grafana_data:/var/lib/grafana
      - ./monitoring/grafana/dashboards:/etc/grafana/provisioning/dashboards
      - ./monitoring/grafana/datasources:/etc/grafana/provisioning/datasources

volumes:
  prometheus_data:
  grafana_data:
`;
    }

    return compose;
}

