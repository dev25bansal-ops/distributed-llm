function generateAnsiblePlaybook(config) {
    const { gpus, model, quantization, security } = config;
    const gpu = GPU_OPTIONS.find(g => g.id === gpus.gpuType);
    const modelInfo = MODEL_OPTIONS.find(m => m.id === model.model);
    const isSecure = security.preset !== 'development';

    return `# ansible/playbook.yml
# DistLLM Cluster Deployment
# Generated by DistLLM Deployment Configurator

---
- name: Deploy DistLLM Cluster
  hosts: all
  become: yes
  vars:
    distllm_model: ${modelInfo.id}
    distllm_quantization: ${quantization.level}
    distllm_api_port: 8000
    distllm_grpc_port: 50050
    ${isSecure ? 'distllm_api_key: "{{ vault_distllm_api_key }}"' : ''}

  tasks:
    - name: Install dependencies
      apt:
        name:
          - docker.io
          - docker-compose
          - nvidia-driver-535
          - nvidia-utils-535
        state: present
        update_cache: yes

    - name: Start Docker service
      systemd:
        name: docker
        state: started
        enabled: yes

    - name: Create DistLLM directory
      file:
        path: /opt/distllm
        state: directory
        owner: root
        group: root
        mode: '0755'

    - name: Copy docker-compose.yml
      template:
        src: docker-compose.yml.j2
        dest: /opt/distllm/docker-compose.yml
      notify: Restart DistLLM

    - name: Create models directory
      file:
        path: /opt/distllm/models
        state: directory

    - name: Download model
      command: >
        docker run --rm -v /opt/distllm/models:/models
        ghcr.io/distributed-llm/model-downloader:latest
        --model {{ distllm_model }}
        --output /models
      args:
        creates: /opt/distllm/models/{{ distllm_model }}

    - name: Start DistLLM cluster
      docker_compose:
        project_src: /opt/distllm
        state: present
      register: distllm_status

    - name: Wait for coordinator to be ready
      uri:
        url: "http://localhost:{{ distllm_api_port }}/health"
        status_code: 200
      register: health_check
      until: health_check.status == 200
      retries: 30
      delay: 10

    - name: Display cluster status
      debug:
        msg: |
          DistLLM cluster is running!
          API: http://{{ ansible_default_ipv4.address }}:{{ distllm_api_port }}
          Model: {{ distllm_model }}
          Quantization: {{ distllm_quantization }}

  handlers:
    - name: Restart DistLLM
      docker_compose:
        project_src: /opt/distllm
        state: present
        restarted: yes

- name: Configure Monitoring
  hosts: coordinator
  become: yes
  tasks:
    - name: Install Prometheus
      apt:
        name: prometheus
        state: present

    - name: Configure Prometheus targets
      template:
        src: prometheus.yml.j2
        dest: /etc/prometheus/prometheus.yml
      notify: Restart Prometheus

    - name: Install Grafana
      apt:
        name: grafana
        state: present

    - name: Start Grafana
      systemd:
        name: grafana-server
        state: started
        enabled: yes

  handlers:
    - name: Restart Prometheus
      systemd:
        name: prometheus
        state: restarted

# ansible/inventory.ini
[coordinator]
coordinator1 ansible_host=<coordinator-ip>

[workers]
worker1 ansible_host=<worker1-ip>
worker2 ansible_host=<worker2-ip>
worker3 ansible_host=<worker3-ip>
worker4 ansible_host=<worker4-ip>

[all:vars]
ansible_user=ubuntu
ansible_ssh_private_key_file=~/.ssh/id_rsa`;
}

